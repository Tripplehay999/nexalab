// Regenerates the Supabase Auth email templates in this folder from
// supabase/functions/send-notification/templates.ts.
// Run from the repo root:  deno run --allow-read --allow-write supabase/templates/generate.ts
import { authEmails } from '../functions/send-notification/templates.ts';

const dir = new URL('.', import.meta.url);
const rows: string[] = [];

for (const email of authEmails()) {
  const header = `<!-- Supabase → Authentication → Emails → "${email.supabaseName}". Subject: ${email.subject}\n     Generated by supabase/templates/generate.ts — edit templates.ts, not this file. -->\n`;
  await Deno.writeTextFile(new URL(email.file, dir), header + email.html);
  rows.push(`| ${email.supabaseName} | \`${email.file}\` | ${email.subject} |`);
}

await Deno.writeTextFile(new URL('README.md', dir), `# Supabase Auth email templates

Branded versions of every email Supabase Auth sends. Paste each file's contents into
**Supabase Dashboard → Authentication → Emails → (template)** and set the subject shown.

| Supabase template | File | Subject |
|---|---|---|
${rows.join('\n')}

The welcome email is not here — it's sent by the \`send-notification\` Edge Function
right after a client's first sign-in.

To change the design or copy, edit \`supabase/functions/send-notification/templates.ts\`
(\`authEmails()\`), then regenerate:

\`\`\`
deno run --allow-read --allow-write supabase/templates/generate.ts
\`\`\`
`);

console.log(`Wrote ${rows.length} templates + README.md`);
